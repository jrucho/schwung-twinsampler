export function fxPresetRow(effect, preset) {
    const i = Math.max(0, Math.min(4, preset | 0));
    const rows = FX_PRESETS[Math.max(0, Math.min(8, effect | 0))];
    return [i / 4, ...rows[i].slice(1)];
}

export function fxPresetName(effect, preset) {
    return FX_PRESETS[Math.max(0, Math.min(8, effect | 0))][Math.max(0, Math.min(4, preset | 0))][0];
}

export function fxPresetDisplayName(effect, params) {
    const preset = Math.max(0, Math.min(4, Math.round(((params && params[0]) || 0) * 4)));
    const row = fxPresetRow(effect, preset);
    const custom = !Array.isArray(params) || row.some((value, i) => Math.abs(value - params[i]) > 0.002);
    return fxPresetName(effect, preset) + (custom ? '*' : '');
}
